"""Seed data for the task-ticket channel.

Everything here is *editable from Discord* afterwards (`/tasks template-add`,
`/tasks template-toggle`); this module is only the starting point.

PHONE templates are copied onto every new phone as a checklist and released
into the channel when the phone reaches the stage named in `trigger`.
Trigger format: "PHONE:<status>" or "REPAIR:<status>", comma-separated for
"any of". `auto` is a trigger at which the ticket is ticked off automatically.

GENERAL templates are business-level. recur=None -> one-off (created by
`/tasks setup-general`); recur=N -> reopened every N days after the last one
is closed.
"""
from __future__ import annotations

from typing import NamedTuple, Optional


class PhoneTpl(NamedTuple):
    code: str
    title: str
    description: str
    category: str
    trigger: str
    priority: str = "NORMAL"
    auto: Optional[str] = None
    due_days: Optional[int] = None


class GeneralTpl(NamedTuple):
    code: str
    title: str
    description: str
    category: str
    priority: str = "NORMAL"
    recur: Optional[int] = None


